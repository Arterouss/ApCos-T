// ApiCos Minimal Service Worker for PWA / TWA support
const CACHE_NAME = 'apicos-pwa-v1';

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
      );
    })
  );
  self.clients.claim();
});

// Network-first strategy: always fetch fresh content, fallback to cache if offline
self.addEventListener('fetch', (event) => {
  // Let browser handle media streaming and proxy requests directly
  if (
    event.request.url.includes('/api/') ||
    event.request.url.includes('.mp4') ||
    event.request.url.includes('.m3u8') ||
    event.request.url.includes('.webm') ||
    event.request.method !== 'GET'
  ) {
    return;
  }

  event.respondWith(
    fetch(event.request)
      .then((response) => {
        // Cache successful responses for static assets
        if (response && response.status === 200 && response.type === 'basic') {
          const responseToCache = response.clone();
          caches.open(CACHE_NAME).then((cache) => {
            cache.put(event.request, responseToCache);
          });
        }
        return response;
      })
      .catch(() => caches.match(event.request))
  );
});
